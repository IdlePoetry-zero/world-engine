"""Opt-in local Windows Speech adapter for authorized narration text.

This adapter follows the Microsoft .NET Framework ``SpeechSynthesizer``
``SetOutputToWaveFile`` pattern. It passes prompt text through UTF-8 stdin to a
fixed PowerShell script, writes WAV output only to a per-call temporary
directory, and never lets plugin code select a path or command:
https://learn.microsoft.com/en-us/dotnet/api/system.speech.synthesis.speechsynthesizer.setoutputtowavefile?view=netframework-4.8.1
"""

from __future__ import annotations

import asyncio
from collections import defaultdict, deque
from dataclasses import dataclass
import os
from pathlib import Path
import shutil
import stat
import subprocess
import tempfile
import time
from typing import Any, Awaitable, Callable
from uuid import UUID, uuid4
from hashlib import sha256

from world_engine.application.media_assets import MAX_MEDIA_ASSET_BYTES
from world_engine.application.media_contracts import (
    GeneratedMedia,
    MediaManifest,
    MediaRegistry,
    MediaRequest,
    MediaSubscription,
)


WINDOWS_SPEECH_PLUGIN_ID = "windows.speech"
WINDOWS_SPEECH_MANIFEST_VERSION = "1.0"
WINDOWS_SPEECH_EVENT_TYPES = (
    "core.time_advanced.v1",
    "core.movement_completed.v1",
    "core.entity_discovered.v1",
    "core.improvised_check_resolved.v1",
    "core.market_trade_executed.v1",
    "core.combat_exchange_resolved.v1",
    "core.combat_retreat_resolved.v1",
    "core.health_restored.v1",
    "core.injury_treated.v1",
    "core.knowledge_acquired.v1",
    "core.goal_created.v1",
    "core.goal_updated.v1",
)

DEFAULT_MAXIMUM_ASSET_BYTES = 16 * 1024 * 1024
DEFAULT_MAXIMUM_PROMPT_BYTES = 32 * 1024
DEFAULT_TIMEOUT_SECONDS = 45.0
DEFAULT_PENDING_ARTIFACTS = 8
DEFAULT_PENDING_BYTES = 64 * 1024 * 1024
DEFAULT_PENDING_TTL_SECONDS = 300.0

_POWER_SHELL_SCRIPT = r"""
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$synth = $null
try {
    [Console]::InputEncoding = [System.Text.UTF8Encoding]::new($false)
    $outputPath = $env:WORLD_ENGINE_SPEECH_OUTPUT
    $voiceName = $env:WORLD_ENGINE_SPEECH_VOICE
    $text = [Console]::In.ReadToEnd()
    if ([string]::IsNullOrWhiteSpace($outputPath) -or [string]::IsNullOrWhiteSpace($text)) {
        exit 2
    }
    Add-Type -AssemblyName System.Speech
    $synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
    try {
        if (-not [string]::IsNullOrWhiteSpace($voiceName)) {
            $synth.SelectVoice($voiceName)
        }
        $synth.SetOutputToWaveFile($outputPath)
        $synth.Speak($text)
    }
    finally {
        if ($null -ne $synth) {
            try { $synth.SetOutputToNull() } catch { }
            $synth.Dispose()
        }
    }
    exit 0
}
catch {
    if ($null -ne $synth) {
        try { $synth.SetOutputToNull() } catch { }
        try { $synth.Dispose() } catch { }
    }
    exit 1
}
""".strip()

ProcessFactory = Callable[..., Awaitable[Any]]


class WindowsSpeechError(RuntimeError):
    """Base failure with no prompt, output path, or provider detail in its text."""


class WindowsSpeechUnavailable(WindowsSpeechError):
    """PowerShell/System.Speech cannot run in the current environment."""


class WindowsSpeechTimeout(WindowsSpeechError):
    """Synthesis exceeded its configured process timeout."""


class WindowsSpeechOutputError(WindowsSpeechError):
    """The child did not produce a bounded, structurally valid WAV file."""


class WindowsSpeechArtifactExpired(WindowsSpeechError):
    """The matching generated bytes expired before the registry fetched them."""


@dataclass(frozen=True, slots=True)
class _PendingArtifact:
    token: UUID
    data: bytes
    expires_at: float
    expiry_handle: asyncio.TimerHandle


class WindowsSpeechAdapter:
    """Registered ``speech`` plugin and byte transport for Windows PowerShell."""

    def __init__(
        self,
        *,
        voice_name: str | None = None,
        powershell_executable: str | Path | None = None,
        temporary_root: str | Path | None = None,
        maximum_asset_bytes: int = DEFAULT_MAXIMUM_ASSET_BYTES,
        maximum_prompt_bytes: int = DEFAULT_MAXIMUM_PROMPT_BYTES,
        timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS,
        maximum_pending_artifacts: int = DEFAULT_PENDING_ARTIFACTS,
        maximum_pending_bytes: int = DEFAULT_PENDING_BYTES,
        pending_ttl_seconds: float = DEFAULT_PENDING_TTL_SECONDS,
        process_factory: ProcessFactory | None = None,
    ):
        if not 0 < maximum_asset_bytes <= MAX_MEDIA_ASSET_BYTES:
            raise ValueError("maximum_asset_bytes is outside the media-store limit")
        if not 0 < maximum_prompt_bytes <= 256 * 1024:
            raise ValueError("maximum_prompt_bytes must be positive and at most 256 KiB")
        if not 0 < timeout_seconds <= 600:
            raise ValueError("timeout_seconds must be positive and at most 600")
        if maximum_pending_artifacts < 1:
            raise ValueError("maximum_pending_artifacts must be positive")
        if maximum_pending_bytes < maximum_asset_bytes:
            raise ValueError("maximum_pending_bytes must fit one maximum-size asset")
        if not 1 <= pending_ttl_seconds <= 3600:
            raise ValueError("pending_ttl_seconds must be between 1 and 3600")
        if voice_name is not None:
            voice_name = voice_name.strip()
            if not voice_name or len(voice_name) > 128 or any(ord(char) < 32 for char in voice_name):
                raise ValueError("voice_name must be nonempty text of at most 128 printable characters")
        if powershell_executable is not None:
            executable = str(powershell_executable)
            if not executable or len(executable) > 1024 or any(ord(char) < 32 for char in executable):
                raise ValueError("powershell_executable must be a bounded path")
            self.powershell_executable = executable
        else:
            self.powershell_executable = None

        requested_temp_root = Path(temporary_root).expanduser() if temporary_root is not None else None
        if requested_temp_root is not None:
            if requested_temp_root.is_symlink():
                raise ValueError("temporary_root cannot be a symbolic link")
            requested_temp_root.mkdir(parents=True, exist_ok=True)
            if not requested_temp_root.is_dir():
                raise ValueError("temporary_root must be a directory")
            self.temporary_root = requested_temp_root.resolve()
        else:
            self.temporary_root = None

        self.voice_name = voice_name
        self.maximum_asset_bytes = maximum_asset_bytes
        self.maximum_prompt_bytes = maximum_prompt_bytes
        self.timeout_seconds = timeout_seconds
        self.maximum_pending_artifacts = maximum_pending_artifacts
        self.maximum_pending_bytes = maximum_pending_bytes
        self.pending_ttl_seconds = pending_ttl_seconds
        self._process_factory = process_factory
        self._pending: dict[tuple[UUID, str], deque[_PendingArtifact]] = defaultdict(deque)
        self._pending_count = 0
        self._pending_size = 0
        self._pending_lock = asyncio.Lock()

    async def generate(self, request: MediaRequest) -> GeneratedMedia:
        """Synthesize only host-approved text and return an immutable receipt."""
        if request.kind != "speech":
            raise ValueError("Windows Speech supports speech requests only")
        prompt = request.authorized_description.encode("utf-8")
        if not prompt or len(prompt) > self.maximum_prompt_bytes:
            raise ValueError("The authorized speech text exceeds the configured input limit")

        data = await self._synthesize(prompt)
        digest = sha256(data).hexdigest()
        receipt = GeneratedMedia(
            request_id=request.request_id,
            content_hash=digest,
            content_type="audio/wav",
            byte_size=len(data),
        )
        await self._remember(request.request_id, digest, data)
        return receipt

    async def fetch(
        self,
        request: MediaRequest,
        receipt: GeneratedMedia,
        *,
        maximum_bytes: int,
    ) -> bytes:
        """Transfer one in-memory artifact to the host without exposing a path."""
        if (
            request.kind != "speech"
            or receipt.request_id != request.request_id
            or receipt.content_type != "audio/wav"
            or receipt.byte_size > min(maximum_bytes, self.maximum_asset_bytes)
        ):
            raise WindowsSpeechOutputError("The speech artifact receipt does not match its request")
        key = (request.request_id, receipt.content_hash)
        async with self._pending_lock:
            self._expire_locked(time.monotonic())
            queue = self._pending.get(key)
            if not queue:
                raise WindowsSpeechArtifactExpired("Generated speech bytes are unavailable")
            item = queue.popleft()
            if not queue:
                self._pending.pop(key, None)
            item.expiry_handle.cancel()
            self._pending_count -= 1
            self._pending_size -= len(item.data)
        if len(item.data) != receipt.byte_size or sha256(item.data).hexdigest() != receipt.content_hash:
            raise WindowsSpeechOutputError("Generated speech bytes do not match the receipt")
        return item.data

    async def close(self) -> None:
        """Release pending artifacts during orderly adapter shutdown."""
        async with self._pending_lock:
            for queue in self._pending.values():
                for item in queue:
                    item.expiry_handle.cancel()
            self._pending.clear()
            self._pending_count = 0
            self._pending_size = 0

    async def _synthesize(self, prompt: bytes) -> bytes:
        if self._process_factory is None and os.name != "nt":
            raise WindowsSpeechUnavailable("Windows Speech is available only on Windows")
        executable = self.powershell_executable or (
            shutil.which("powershell.exe") if self._process_factory is None else "powershell.exe"
        )
        if executable is None:
            raise WindowsSpeechUnavailable("Windows PowerShell is unavailable")

        with tempfile.TemporaryDirectory(
            prefix="world-engine-speech-",
            dir=str(self.temporary_root) if self.temporary_root is not None else None,
        ) as temporary_name:
            temporary_dir = Path(temporary_name)
            if os.name != "nt":
                os.chmod(temporary_dir, 0o700)
            output_path = temporary_dir / "speech.wav"
            environment = self._child_environment(temporary_dir, output_path)
            factory = self._process_factory or asyncio.create_subprocess_exec
            creationflags = getattr(subprocess, "CREATE_NO_WINDOW", 0) if os.name == "nt" else 0
            try:
                process = await factory(
                    executable,
                    "-NoLogo",
                    "-NoProfile",
                    "-NonInteractive",
                    "-STA",
                    "-Command",
                    _POWER_SHELL_SCRIPT,
                    stdin=asyncio.subprocess.PIPE,
                    stdout=asyncio.subprocess.DEVNULL,
                    stderr=asyncio.subprocess.DEVNULL,
                    cwd=str(temporary_dir),
                    env=environment,
                    creationflags=creationflags,
                )
            except OSError as exc:
                raise WindowsSpeechUnavailable("Windows PowerShell could not be started") from exc

            try:
                await asyncio.wait_for(process.communicate(input=prompt), timeout=self.timeout_seconds)
            except asyncio.TimeoutError as exc:
                await self._kill_and_wait(process)
                raise WindowsSpeechTimeout("Windows Speech exceeded its process timeout") from exc
            except asyncio.CancelledError:
                await self._kill_and_wait(process)
                raise
            if process.returncode != 0:
                raise WindowsSpeechError("Windows Speech exited without producing an asset")
            return self._read_bounded_wav(output_path)

    async def _remember(self, request_id: UUID, digest: str, data: bytes) -> None:
        key = (request_id, digest)
        async with self._pending_lock:
            self._expire_locked(time.monotonic())
            if (
                len(data) > self.maximum_asset_bytes
                or self._pending_count >= self.maximum_pending_artifacts
                or self._pending_size + len(data) > self.maximum_pending_bytes
            ):
                raise WindowsSpeechOutputError("Pending speech artifacts exceed the configured memory limit")
            loop = asyncio.get_running_loop()
            token = uuid4()
            expires_at = time.monotonic() + self.pending_ttl_seconds
            expiry_handle = loop.call_later(
                self.pending_ttl_seconds,
                lambda: asyncio.create_task(self._expire_token(key, token)),
            )
            self._pending[key].append(_PendingArtifact(token, data, expires_at, expiry_handle))
            self._pending_count += 1
            self._pending_size += len(data)

    async def _expire_token(self, key: tuple[UUID, str], token: UUID) -> None:
        async with self._pending_lock:
            queue = self._pending.get(key)
            if not queue:
                return
            retained: deque[_PendingArtifact] = deque()
            for item in queue:
                if item.token == token:
                    self._pending_count -= 1
                    self._pending_size -= len(item.data)
                else:
                    retained.append(item)
            if retained:
                self._pending[key] = retained
            else:
                self._pending.pop(key, None)

    def _expire_locked(self, now: float) -> None:
        for key, queue in tuple(self._pending.items()):
            retained: deque[_PendingArtifact] = deque()
            for item in queue:
                if item.expires_at <= now:
                    item.expiry_handle.cancel()
                    self._pending_count -= 1
                    self._pending_size -= len(item.data)
                else:
                    retained.append(item)
            if retained:
                self._pending[key] = retained
            else:
                self._pending.pop(key, None)

    async def _kill_and_wait(self, process: Any) -> None:
        if process.returncode is not None:
            return
        try:
            process.kill()
        except ProcessLookupError:
            pass
        try:
            await asyncio.wait_for(process.wait(), timeout=5.0)
        except asyncio.TimeoutError as exc:
            raise WindowsSpeechError("Windows PowerShell did not stop after cancellation") from exc

    def _child_environment(self, temporary_dir: Path, output_path: Path) -> dict[str, str]:
        # Do not inherit API keys or application-specific environment values.
        safe_names = ("SystemRoot", "WINDIR", "PATH", "COMSPEC")
        environment = {
            name: os.environ[name]
            for name in safe_names
            if name in os.environ
        }
        environment["TEMP"] = str(temporary_dir)
        environment["TMP"] = str(temporary_dir)
        environment["WORLD_ENGINE_SPEECH_OUTPUT"] = str(output_path)
        environment["WORLD_ENGINE_SPEECH_VOICE"] = self.voice_name or ""
        return environment

    def _read_bounded_wav(self, output_path: Path) -> bytes:
        try:
            info = output_path.lstat()
            if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
                raise WindowsSpeechOutputError("Windows Speech output is not a regular WAV file")
            if info.st_size < 12 or info.st_size > self.maximum_asset_bytes:
                raise WindowsSpeechOutputError("Windows Speech output exceeds the configured asset size")
            flags = os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0)
            descriptor = os.open(output_path, flags)
            with os.fdopen(descriptor, "rb") as stream:
                descriptor = -1
                file_info = os.fstat(stream.fileno())
                if not stat.S_ISREG(file_info.st_mode):
                    raise WindowsSpeechOutputError("Windows Speech output is not a regular WAV file")
                data = stream.read(self.maximum_asset_bytes + 1)
        except WindowsSpeechError:
            raise
        except OSError as exc:
            raise WindowsSpeechOutputError("Windows Speech output could not be read safely") from exc
        finally:
            if "descriptor" in locals() and descriptor >= 0:
                os.close(descriptor)
        if len(data) > self.maximum_asset_bytes or len(data) != info.st_size:
            raise WindowsSpeechOutputError("Windows Speech output changed or exceeded its size limit")
        if (
            data[:4] != b"RIFF"
            or data[8:12] != b"WAVE"
            or int.from_bytes(data[4:8], "little") + 8 != len(data)
        ):
            raise WindowsSpeechOutputError("Windows Speech did not produce a complete RIFF/WAVE file")
        return data


def register_windows_speech(
    registry: MediaRegistry,
    *,
    voice_name: str | None = None,
    powershell_executable: str | Path | None = None,
    temporary_root: str | Path | None = None,
    maximum_asset_bytes: int = DEFAULT_MAXIMUM_ASSET_BYTES,
    timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS,
    plugin_id: str = WINDOWS_SPEECH_PLUGIN_ID,
    manifest_version: str = WINDOWS_SPEECH_MANIFEST_VERSION,
    process_factory: ProcessFactory | None = None,
) -> WindowsSpeechAdapter:
    """Register local speech without enabling it in application startup."""
    if process_factory is None:
        if os.name != "nt":
            raise WindowsSpeechUnavailable("Windows Speech is available only on Windows")
        if powershell_executable is None and shutil.which("powershell.exe") is None:
            raise WindowsSpeechUnavailable("Windows PowerShell is unavailable")
    adapter = WindowsSpeechAdapter(
        voice_name=voice_name,
        powershell_executable=powershell_executable,
        temporary_root=temporary_root,
        maximum_asset_bytes=maximum_asset_bytes,
        timeout_seconds=timeout_seconds,
        process_factory=process_factory,
    )
    manifest = MediaManifest(
        id=plugin_id,
        version=manifest_version,
        capabilities={"speech"},
        subscriptions=[
            MediaSubscription(event_type=event_type, kind="speech")
            for event_type in WINDOWS_SPEECH_EVENT_TYPES
        ],
        maximum_asset_bytes=maximum_asset_bytes,
    )
    registry.register(manifest, adapter, artifact_transport=adapter)
    return adapter

