import json
from uuid import uuid4

from fastapi.testclient import TestClient

from world_engine.api.app import create_app
from world_engine.api.security import LocalSession
from world_engine.application.authoring import AuthoringApplication
from world_engine.application.operations import OperationsStore
from world_engine.application.worlds import WorldApplication
from world_engine.domain.components import (
    PopulationAgeCohort,
    PopulationAgeRate,
    PopulationComponent,
    PopulationOccupationProfile,
    PopulationSeatPolicy,
)
from world_engine.domain.models import AccessScope, NewWorld, WorldEntity, WorldState
from world_engine.storage.database import Database
from world_engine.storage.repository import WorldRepository


def test_population_author_preview_commits_only_the_civic_seat_policy_change(tmp_path):
    scope = AccessScope(tenant_id=uuid4(), user_id=uuid4())
    player_id, home_id, group_id, new_group_id = uuid4(), uuid4(), uuid4(), uuid4()
    database = Database(f"sqlite:///{(tmp_path / 'world.db').as_posix()}")
    database.create_schema()
    repository = WorldRepository(database)

    population = PopulationComponent(
        species_id="core.human",
        headcount=42,
        unmodeled_headcount=42,
        age_rates=[PopulationAgeRate(age_years=age) for age in range(201)],
        age_cohorts=[PopulationAgeCohort(age_years=age, headcount=42 if age == 35 else 0) for age in range(201)],
        last_advanced_year=1,
        seat_policy=PopulationSeatPolicy(
            revision=7,
            non_player_seat_capacity=2,
            home_place_ids=[home_id],
            extra_given_names=["Ari", "Bea"],
            extra_family_names=["North", "Vale"],
            extra_roles=["artisan", "farmer"],
            occupation_profile=PopulationOccupationProfile(role_weights={"artisan": 2}),
            maintain_civic_occupations=False,
            lifespan_min_years=82,
            lifespan_max_years=100,
            seed_id=uuid4(),
            promotion_serial=2**63 - 1,
        ),
    )
    created = repository.create_world(scope, NewWorld(title="Seat policy authoring", state=WorldState(
        player_id=player_id,
        entities={
            player_id: WorldEntity(id=player_id, kind="character", name="Writer", location_id=home_id),
            home_id: WorldEntity(id=home_id, kind="place", name="North settlement"),
            group_id: WorldEntity(
                id=group_id, kind="group", name="North residents", location_id=home_id,
                components={"population": population.model_dump(mode="json")},
            ),
            new_group_id: WorldEntity(
                id=new_group_id, kind="group", name="South residents", location_id=home_id,
                components={"population": PopulationComponent(
                    species_id="core.human", headcount=17, unmodeled_headcount=17,
                ).model_dump(mode="json")},
            ),
        },
    )))
    branch_id = created.branch.branch_id
    world_id = created.world.world_id
    original = repository.read_world(scope, world_id, branch_id).state.entities[group_id].components["population"]

    service = AuthoringApplication(repository, OperationsStore(tmp_path / "operations.db"))
    session = LocalSession(str(scope.user_id), str(scope.tenant_id), frozenset({"http://testserver"}))
    app = create_app(WorldApplication(repository, None), session, authoring=service)
    prefix = f"/api/v1/worlds/{world_id}/interventions"
    replacement = json.loads(json.dumps(original))
    replacement["seat_policy"].update({
        # Revisions are generated by the server, including nested revisions.
        "revision": 0,
        "maintain_civic_occupations": True,
        "occupation_profile": {"role_weights": {"artisan": 2, "farmer": 1}},
    })
    proposal = {
        "patch_proposal": {
            "entity_id": str(group_id),
            "component_name": "population",
            "replacement": replacement,
            "reason": "Prioritize civic occupations",
        },
    }

    try:
        with TestClient(app) as client:
            client.get("/api/v1/session").raise_for_status()
            new_population = repository.read_world(scope, world_id, branch_id).state.entities[
                new_group_id
            ].components["population"]
            new_policy = json.loads(json.dumps(replacement["seat_policy"]))
            new_policy["revision"] = 0
            new_component = json.loads(json.dumps(new_population)) | {"seat_policy": new_policy}
            first_policy = client.post(prefix + "/preview", json={
                "patch_proposal": proposal["patch_proposal"] | {
                    "entity_id": str(new_group_id), "replacement": new_component,
                },
            }).raise_for_status().json()
            assert first_policy["before"].get("seat_policy") is None
            assert first_policy["after"]["seat_policy"]["revision"] == 1

            equivalent = json.loads(json.dumps(original))
            equivalent["last_advanced_year"] = str(equivalent["last_advanced_year"])
            equivalent["seat_policy"]["promotion_serial"] = str(2**63 - 1)
            equivalent["seat_policy"]["revision"] = 0
            unchanged = client.post(prefix + "/preview", json={
                "patch_proposal": proposal["patch_proposal"] | {"replacement": equivalent},
            }).raise_for_status().json()
            assert unchanged["after"]["seat_policy"]["revision"] == 7
            assert unchanged["after"]["seat_policy"]["promotion_serial"] == str(2**63 - 1)

            preview = client.post(prefix + "/preview", json=proposal).raise_for_status().json()
            before = preview["before"]
            after = preview["after"]

            assert before["headcount"] == after["headcount"] == str(original["headcount"])
            assert before["unmodeled_headcount"] == after["unmodeled_headcount"] == str(original["unmodeled_headcount"])
            assert before["last_advanced_year"] == after["last_advanced_year"] == "1"
            assert before["seat_policy"]["promotion_serial"] == str(2**63 - 1)
            assert after["seat_policy"]["promotion_serial"] == str(2**63 - 1)
            assert after["revision"] == original["revision"] + 1
            assert before["seat_policy"]["revision"] == 7
            assert after["seat_policy"]["revision"] == 8
            assert after["seat_policy"]["maintain_civic_occupations"] is True
            assert after["seat_policy"]["occupation_profile"]["role_weights"] == {"artisan": 2, "farmer": 1}
            assert after["seat_policy"]["extra_roles"] == original["seat_policy"]["extra_roles"]
            assert after["seat_policy"]["home_place_ids"] == original["seat_policy"]["home_place_ids"]
            assert repository.read_world(scope, world_id, branch_id).state.entities[group_id].components["population"] == original

            commit = client.post(prefix, json={
                "preview_id": preview["preview_id"], "expected_version": preview["expected_version"],
            }).raise_for_status().json()
            assert commit["state_version"] == "1"

        committed = repository.read_world(scope, world_id, branch_id)
        final_population = committed.state.entities[group_id].components["population"]
        assert final_population["headcount"] == original["headcount"]
        assert final_population["unmodeled_headcount"] == original["unmodeled_headcount"]
        assert final_population["age_rates"] == original["age_rates"]
        assert final_population["age_cohorts"] == original["age_cohorts"]
        assert final_population["last_advanced_year"] == original["last_advanced_year"]
        assert final_population["seat_policy"]["extra_roles"] == original["seat_policy"]["extra_roles"]
        assert final_population["seat_policy"]["revision"] == 8
        assert final_population["seat_policy"]["promotion_serial"] == 2**63 - 1
        assert repository.replay(scope, world_id, branch_id).state_hash == committed.state_hash
    finally:
        database.dispose()
